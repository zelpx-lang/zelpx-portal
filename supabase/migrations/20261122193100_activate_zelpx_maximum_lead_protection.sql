-- ZELPX Maximum Lead Protection activation.
-- Apply only after the updated customer portal is deployed.
-- Any pre-deployment request without a server-recorded confirmation is grandfathered.

-- "Unable to reach" claims need documented, spaced contact attempts.
-- Immediate claims remain available for invalid numbers, wrong persons, duplicates,
-- and explicit customer denial.
create or replace function public.submit_lead_protection_claim(p_purchase_id uuid,p_reason text,p_details text default null)
returns uuid language plpgsql security definer set search_path=''
as $function$
declare v_purchase public.lead_purchases%rowtype; v_claim_id uuid; v_attempt_count integer; v_first_attempt timestamptz; v_last_attempt timestamptz;
begin
 if auth.uid() is null then raise exception 'You must be signed in.'; end if;
 if p_reason not in ('invalid_phone','customer_denies_request','wrong_person','duplicate_lead','fake_customer','false_service_request','unable_to_reach','other') then
  raise exception 'Choose a valid claim reason.';
 end if;
 select lp.* into v_purchase from public.lead_purchases lp
 join public.contractors c on c.id=lp.contractor_id
 where lp.id=p_purchase_id and c.user_id=auth.uid() for update of lp;
 if not found then raise exception 'Purchased lead not found for this contractor.'; end if;
 if v_purchase.purchased_at < now()-interval '7 days' then raise exception 'The 7-day lead protection claim period has expired.'; end if;
 if p_reason='unable_to_reach' then
  select count(*),min(created_at),max(created_at)
  into v_attempt_count,v_first_attempt,v_last_attempt
  from public.lead_contact_attempts where purchase_id=p_purchase_id
    and outcome in ('no_answer','voicemail','message_sent');
  if coalesce(v_attempt_count,0)<3 or v_last_attempt-v_first_attempt<interval '24 hours' then
   raise exception 'For an unable-to-reach claim, record at least 3 contact attempts spanning 24 hours first.';
  end if;
 end if;
 insert into public.lead_protection_claims(purchase_id,lead_id,contractor_id,reason,details)
 values(v_purchase.id,v_purchase.lead_id,v_purchase.contractor_id,p_reason,left(coalesce(p_details,''),2000))
 returning id into v_claim_id;
 return v_claim_id;
end;
$function$;

revoke all on function public.submit_lead_protection_claim(uuid,text,text) from public,anon;
grant execute on function public.submit_lead_protection_claim(uuid,text,text) to authenticated;


-- Do not let a browser/client forge the server timestamp that represents
-- the customer's explicit confirmation. Only confirm_own_service_request may set it.
create or replace function private.guard_service_request_confirmation_fields()
returns trigger language plpgsql security definer
set search_path='pg_catalog','public','auth','private'
as $function$
begin
 if tg_op='INSERT' then
  new.customer_live_confirmed_at:=null;
  new.customer_live_confirmation_version:=null;
 elsif (
   new.customer_live_confirmed_at is distinct from old.customer_live_confirmed_at
   or new.customer_live_confirmation_version is distinct from old.customer_live_confirmation_version
 ) and coalesce(current_setting('zelpx.confirmation_write',true),'')<>'true' then
  raise exception 'Customer confirmation can only be recorded through the ZELPX confirmation flow.';
 end if;
 return new;
end;
$function$;

drop trigger if exists service_request_guard_confirmation_fields on public.service_requests;
create trigger service_request_guard_confirmation_fields
before insert or update of customer_live_confirmed_at,customer_live_confirmation_version
on public.service_requests
for each row execute function private.guard_service_request_confirmation_fields();

-- Recreate the confirmation RPC so the trusted server-side write is explicitly
-- marked for the trigger above. The timestamp is generated by PostgreSQL.
drop function if exists public.confirm_own_service_request(uuid);

create or replace function public.confirm_own_service_request(p_request_id uuid,p_customer_attested boolean)
returns jsonb language plpgsql security definer set search_path=''
as $function$
declare v_user_email_confirmed boolean; v_confirmed_at timestamptz;
begin
 if auth.uid() is null then raise exception 'You must be signed in.'; end if;
 if p_customer_attested is distinct from true then
  raise exception 'Confirm that this is a real project and that you are ready to be contacted.';
 end if;
 select (u.email_confirmed_at is not null) into v_user_email_confirmed
 from auth.users u where u.id=auth.uid();
 if not coalesce(v_user_email_confirmed,false) then
  raise exception 'Verify your email before confirming this service request.';
 end if;
 perform pg_catalog.set_config('zelpx.confirmation_write','true',true);
 update public.service_requests
 set customer_live_confirmed_at=pg_catalog.now(),
     customer_live_confirmation_version='2026-11-22-v1'
 where id=p_request_id and user_id=auth.uid() and status='new' and lead_id is null
   and commercial_sharing_consent_at is not null
   and coalesce(pg_catalog.btrim(commercial_sharing_consent_version),'')<>'';
 if not found then raise exception 'Request not found, already processed, or commercial sharing consent is missing.'; end if;
 select customer_live_confirmed_at into v_confirmed_at
 from public.service_requests where id=p_request_id;
 return jsonb_build_object('success',true,'confirmed_at',v_confirmed_at);
end;
$function$;

revoke all on function public.confirm_own_service_request(uuid,boolean) from public,anon;
grant execute on function public.confirm_own_service_request(uuid,boolean) to authenticated;

update public.service_requests
set protection_required=false
where customer_live_confirmed_at is null;

create or replace function private.force_service_request_protection_fields()
returns trigger language plpgsql security definer set search_path='pg_catalog','public','auth','private'
as $function$
begin
 if tg_op='INSERT' then
  new.protection_required:=true;
  new.customer_live_confirmed_at:=null;
  new.customer_live_confirmation_version:=null;
 elsif new.protection_required is distinct from old.protection_required
   and new.protection_required=false
   and not exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin') then
  raise exception 'Only an administrator can change lead protection enforcement.';
 end if;
 return new;
end;
$function$;

drop trigger if exists service_request_force_protection_fields on public.service_requests;
create trigger service_request_force_protection_fields
before insert or update of protection_required on public.service_requests
for each row execute function private.force_service_request_protection_fields();

create or replace function private.enforce_service_request_protection()
returns trigger language plpgsql security definer set search_path='pg_catalog','public','auth','private'
as $function$
declare v_email_confirmed boolean; v_risk_level text; v_checks jsonb;
begin
 if new.lead_id is null or new.status<>'published' or not coalesce(new.protection_required,true) then return new; end if;
 if new.customer_live_confirmed_at is null or coalesce(trim(new.customer_live_confirmation_version),'')=''
    or new.commercial_sharing_consent_at is null or coalesce(trim(new.commercial_sharing_consent_version),'')='' then
  raise exception 'Customer confirmation is required before this request can be published.';
 end if;
 select (u.email_confirmed_at is not null) into v_email_confirmed from auth.users u where u.id=new.user_id;
 if not coalesce(v_email_confirmed,false) then raise exception 'Customer email must be verified before this request can be published.'; end if;
 select risk_level,checks into v_risk_level,v_checks from public.lead_verification_checks where request_id=new.id;
 if not found then raise exception 'Automatic lead verification has not completed. Please retry review.'; end if;
 if v_risk_level='high'
    or coalesce((v_checks->>'same_customer_duplicate')::boolean,false)
    or coalesce((v_checks->>'duplicate_description')::boolean,false)
    or not coalesce((v_checks->>'zip_format_valid')::boolean,false) then
  raise exception 'ZELPX protection review blocked this lead. Resolve the verification flags before publishing.';
 end if;
 return new;
end;
$function$;

drop trigger if exists service_request_protection_before_publish on public.service_requests;
create trigger service_request_protection_before_publish before update of lead_id,status on public.service_requests
for each row execute function private.enforce_service_request_protection();
